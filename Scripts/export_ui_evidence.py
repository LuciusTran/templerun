#!/usr/bin/env python3
"""Export original English strings and retain the byte-verified native UI analysis.

Requires PyYAML. --analysis points at the existing local APK analysis directory.
The working prefab is generated by TempleRunUIBuilder in Unity, not by this script.
"""
import argparse
import hashlib
import json
import re
import shutil
import struct
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--analysis', type=Path)
args = parser.parse_args()

def unity_yaml(path):
    value = re.sub(r'^%.*\n|^--- !u!\d+ &-?\d+\n', '', path.read_text(), flags=re.M)
    return yaml.load(value, Loader=yaml.BaseLoader)['MonoBehaviour']

shared = unity_yaml(ROOT / 'Assets/Localization/TempleRunLocTable Shared Data.asset')
localized = unity_yaml(ROOT / 'Assets/Localization/TempleRunLocTable_en.asset')
keys = {entry['m_Id']: entry['m_Key'] for entry in shared['m_Entries']}
strings = {}
for entry in localized['m_TableData']:
    strings[keys[entry['m_Id']]] = entry['m_Localized']
# Legacy keys are kept verbatim too; malformed legacy lines are excluded explicitly.
legacy = (ROOT / 'Assets/Resources/Strings.txt').read_text()
for key, value in re.findall(r'^"([^"\n]+)"\s*=\s*"([^"\n]*)";?\s*$', legacy, re.M):
    strings[key] = value.replace('\\n', '\n')
output = {'entries': [{'key': k, 'value': v} for k, v in sorted(strings.items())]}
encoded = json.dumps(output, ensure_ascii=False, indent=2) + '\n'
(ROOT / 'Evidence/ui-english-strings.json').write_text(encoded)
(ROOT / 'Assets/Resources/TempleRunUIEnglish.json').write_text(encoded)
report = {'inputs': [], 'stringCount': len(strings), 'nativeUIBodies': [], 'limitations': [
    'Rendering, pointer input and local gameplay/profile service bindings are compatibility adapters.',
    'Original transition coroutines, title fly-in, platform purchases, ads and remote events are not restored.'
]}
for path in ['Assets/Scenes/GamePlay.unity', 'Assets/Localization/TempleRunLocTable Shared Data.asset',
             'Assets/Localization/TempleRunLocTable_en.asset', 'Assets/Resources/Strings.txt']:
    report['inputs'].append({'path': path, 'sha256': hashlib.sha256((ROOT / path).read_bytes()).hexdigest()})
if args.analysis:
    for folder in ['DecompiledUI', 'DecompiledUIExtra', 'DecompiledUIThird', 'DecompiledUIFourth']:
        for path in sorted((args.analysis / folder).glob('*/*.cpp')):
            relative = path.relative_to(args.analysis / folder)
            target = ROOT / 'DecompiledNative' / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
            report['nativeUIBodies'].append(str(target.relative_to(ROOT)))
    binary = args.analysis / 'Extracted/lib/arm64-v8a/libil2cpp.so'
    with binary.open('rb') as stream:
        # Ghidra read-only import uses +0x100000; this address is in PT_LOAD[0].
        stream.seek(0x7a3b10 - 0x100000)
        threshold = struct.unpack('<d', stream.read(8))[0]
    if threshold != 1.9: raise ValueError('Unexpected native aspect threshold')
    report['aspectThreshold'] = {'ghidraAddress': '0x7a3b10', 'elfVirtualAddress': '0x6a3b10', 'value': threshold}
report['nativeUIBodies'] = sorted(set(report['nativeUIBodies']))
(ROOT / 'Evidence/ui-source-evidence.json').write_text(json.dumps(report, indent=2)+'\n')
print(f'Exported {len(strings)} original English strings; retained {len(report["nativeUIBodies"])} native UI bodies')
